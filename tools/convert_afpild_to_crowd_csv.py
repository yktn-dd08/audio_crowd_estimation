"""Convert one-second AFPILD trajectories to ATC-style crowd CSV files.

Each input trajectory becomes one CSV containing one person and one WKT
LINESTRING row with the standard columns: id,start_time,geom.
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import shutil
import tempfile
from datetime import datetime
from pathlib import Path

from shapely import wkt
from shapely.geometry import LineString


NAME_PATTERN = re.compile(
    r"s(?P<subject>\d{2})_(?P<session>[1-4])_footstep_trajectory_1s\.csv$"
)
OUTPUT_PATTERN = "s??_?_crowd.csv"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert AFPILD one-second trajectories to ATC-style CSV files."
    )
    parser.add_argument("input_dir", type=Path, help="AFPILD_v1_aligned_1s directory")
    parser.add_argument("output_dir", type=Path, help="Destination crowd/org directory")
    parser.add_argument(
        "--start-time",
        default="2023-05-17 00:00:00",
        help="Synthetic start timestamp in YYYY-MM-DD HH:MM:SS format.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace files generated by an earlier run; unrelated files are preserved.",
    )
    return parser.parse_args()


def read_trajectory(path: Path) -> tuple[str, list[tuple[float, float]]]:
    with path.open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))
    if not rows or list(rows[0]) != ["t", "pid", "x", "y"]:
        raise ValueError(f"Unexpected trajectory schema: {path}")
    times = [float(row["t"]) for row in rows]
    if times != [float(index) for index in range(len(rows))]:
        raise ValueError(f"Trajectory is not sampled at one-second intervals: {path}")
    pids = {row["pid"] for row in rows}
    if len(pids) != 1:
        raise ValueError(f"Expected exactly one person: {path}")
    coordinates = [(float(row["x"]), float(row["y"])) for row in rows]
    if len(coordinates) < 2:
        raise ValueError(f"At least two coordinates are required: {path}")
    return pids.pop(), coordinates


def linestring_wkt(coordinates: list[tuple[float, float]]) -> str:
    points = ", ".join(f"{x:.10f} {y:.10f}" for x, y in coordinates)
    return f"LINESTRING ({points})"


def write_crowd_csv(
    path: Path, person_id: str, start_time: str, coordinates: list[tuple[float, float]]
) -> None:
    with path.open("w", encoding="utf-8", newline="") as output:
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(["id", "start_time", "geom"])
        writer.writerow([person_id, start_time, linestring_wkt(coordinates)])


def validate_file(
    path: Path,
    expected_id: str,
    expected_start_time: str,
    expected_coordinates: list[tuple[float, float]],
) -> None:
    with path.open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))
    if len(rows) != 1 or list(rows[0]) != ["id", "start_time", "geom"]:
        raise ValueError(f"Expected one ATC-style trajectory row: {path}")
    row = rows[0]
    if row["id"] != expected_id or row["start_time"] != expected_start_time:
        raise ValueError(f"ID or start time mismatch: {path}")
    geometry = wkt.loads(row["geom"])
    if not isinstance(geometry, LineString):
        raise ValueError(f"Geometry is not a LINESTRING: {path}")
    actual_coordinates = list(geometry.coords)
    if actual_coordinates != expected_coordinates:
        raise ValueError(f"Coordinate mismatch: {path}")


def main() -> None:
    args = parse_args()
    input_dir = args.input_dir.resolve()
    output_dir = args.output_dir.resolve()
    datetime.strptime(args.start_time, "%Y-%m-%d %H:%M:%S")
    if not input_dir.is_dir():
        raise NotADirectoryError(input_dir)

    source_files = sorted(input_dir.glob("S??/*_trajectory_1s.csv"))
    if len(source_files) != 160:
        raise ValueError(f"Expected 160 trajectories, got {len(source_files)}")

    output_dir.parent.mkdir(parents=True, exist_ok=True)
    temporary_dir = Path(
        tempfile.mkdtemp(prefix=f".{output_dir.name}-", dir=output_dir.parent)
    )
    generated: list[tuple[Path, str, list[tuple[float, float]]]] = []
    try:
        for source_path in source_files:
            match = NAME_PATTERN.fullmatch(source_path.name)
            if match is None:
                raise ValueError(f"Unexpected trajectory filename: {source_path}")
            subject_id = str(int(match.group("subject")))
            session = int(match.group("session"))
            source_pid, coordinates = read_trajectory(source_path)
            if int(source_pid) != int(subject_id):
                raise ValueError(f"Filename and pid disagree: {source_path}")
            output_name = f"s{int(subject_id):02d}_{session}_crowd.csv"
            temporary_path = temporary_dir / output_name
            write_crowd_csv(
                temporary_path, subject_id, args.start_time, coordinates
            )
            validate_file(
                temporary_path, subject_id, args.start_time, coordinates
            )
            generated.append((temporary_path, output_name, coordinates))

        if len(generated) != 160:
            raise ValueError(f"Expected 160 outputs, got {len(generated)}")
        if len({name for _, name, _ in generated}) != 160:
            raise ValueError("Output filenames are not unique")

        output_dir.mkdir(parents=True, exist_ok=True)
        collisions = [output_dir / name for _, name, _ in generated if (output_dir / name).exists()]
        if collisions and not args.overwrite:
            raise FileExistsError(
                f"{len(collisions)} output files already exist; pass --overwrite to replace them"
            )
        for temporary_path, name, _ in generated:
            os.replace(temporary_path, output_dir / name)
        print(
            f"Created {len(generated)} one-person ATC-style CSV files in {output_dir}"
        )
    except Exception:
        shutil.rmtree(temporary_dir, ignore_errors=True)
        raise
    else:
        shutil.rmtree(temporary_dir, ignore_errors=True)


if __name__ == "__main__":
    main()
